def dis(x):
    op=(x>>27)&0o777; ac=(x>>23)&0o17; i=(x>>22)&1; xr=(x>>18)&0o17; y=x&0o777777
    n=OPS.get(op,'%03o?'%op)
    s='%-6s %2o,'%(n,ac)
    s+=('@' if i else '')+('%o'%y)
    if xr: s+='(%o)'%xr
    return s


def dis(word, addr=None, symtab=None):
    op=(word>>27)&0o777
    ac=(word>>23)&0o17
    i=(word>>22)&1
    x=(word>>18)&0o17
    y=word&0o777777
    name=OPS.get(op,"?%03o"%op)
    if op==0o254 and ac in JRSTAC: name=JRSTAC[ac]
    ea="%o"%y
    if symtab and y in symtab: ea=symtab[y]
    s=""
    if op==0o254 and ac in JRSTAC:
        s="%-8s %s%s%s"%(name,"@" if i else "",ea,",%o"%x if x else "")
    elif op==0o047:
        s="%-8s %s"%("CALLI", CALLI.get(y,"%o"%y) if not i and not x else ea)
        if ac: s+="  ; ac=%o"%ac
    elif op==0o051:
        s="%-8s %o,%s%s"%("TTCALL",ac,"@" if i else "",ea)
        if ac in TTCALL: s="%-8s %s%s"%(TTCALL[ac],"@" if i else "",ea)
    else:
        s="%-8s %o,%s%s%s"%(name,ac,"@" if i else "",ea,"(%o)"%x if x else "")
    return s

def s6(x):
    return ''.join(chr(((x>>(30-6*i))&0o77)+32) for i in range(6))
def s7(x):
    return ''.join(chr((x>>(29-7*i))&0x7f) for i in range(5))


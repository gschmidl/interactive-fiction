      SUBROUTINE GETIN(WORD1,WORD2,WORD3)
C     & ,Get Input from Terminal <250929.1142>
C 
C  GET A COMMAND FROM THE ADVENTURER.  SNARF OUT THE FIRST WORD, PAD
C  IT WITH BLANKS, AND RETURN IT IN WORD1. ANY NUMBER OF BLANKS MAY 
C  FOLLOW THE WORD.  IF A SECOND WORD APPEARS, IT IS RETURNED IN  
C  WORD2, ELSE WORD2 IS SET TO BLANKS. UP TO 16 CHARACTERS ARE
C  ALLOWED IN EACH WORD. WORD3 IS NOT USED NORMALLY.
C 
C  THIS ROUTINE IS ALMOST COMPLETELY DIFFERENT FROM THE PDP-11 VERSION. 
C 
      IMPLICIT NONE 
C 
      include 'ioccom.fi'
C 
      INTEGER*2 WORD1(8),WORD2(8),WORD3(8)
      INTEGER*2 TEMP1(8),TEMP2(8),TEMP3(8)
      INTEGER*2 I,TRIMLEN 
      CHARACTER*16 MESS1,MESS2,MESS3
      CHARACTER*48 BUFFER 
C 
      EQUIVALENCE (TEMP1,MESS1),(TEMP2,MESS2),(TEMP3,MESS3) 
C 
      NOINPT=.FALSE.
      IF(BLKLIN) WRITE(CRT,'(" ")') 
  100 WRITE(CRT,200)
  200 FORMAT(">",$)
      READ(KBD,300,END=9000) BUFFER
  300 FORMAT(A48) 
      CALL CASEFOLD(BUFFER) 
      IF(TRIMLEN(BUFFER).LT.1) THEN 
        CALL MSPEK(29)
        GO TO 100 
      ENDIF 
      DO I=1,8
        TEMP1(I)=8224 
        TEMP2(I)=8224 
        TEMP3(I)=8224 
      ENDDO 
C 
C  PARSE STRING INTO THREE WORDS
C 
      CALL SPLITSTRING(BUFFER,MESS1,MESS3)
      CALL SPLITSTRING(MESS3,MESS2,MESS3) 
C 
C  RETURN THREE INPUT WORD ARRAYS IN UPPER CASE 
C 
      DO I=1,8
        WORD1(I)=TEMP1(I) 
        WORD2(I)=TEMP2(I) 
        WORD3(I)=TEMP3(I) 
      ENDDO 
      IF(WORD2(1).EQ.8224) WORD2(1)=0 
      IF(WORD3(1).EQ.8224) WORD3(1)=0 
C 
D     WRITE(CRT,500) WORD1,WORD2,WORD3
D 500 FORMAT("GETIN returns: ",8A2,1X,8A2,1X,8A2) 
C 
      RETURN
C 
 9000 WRITE(CRT,'(/"[end of input]")')
      CALL EXIT
      END 

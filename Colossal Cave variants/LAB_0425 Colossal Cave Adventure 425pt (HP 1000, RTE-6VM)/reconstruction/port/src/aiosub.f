      LOGICAL*2 FUNCTION YESX(X,Y,Z,SPK)
C     & ,Get Yes/No from Terminal <250929.1142>
C 
C  PRINT MESSAGE X, WAIT FOR YES/NO ANSWER.  IF YES, PRINT Y AND LEAVE YEA
C  TRUE; IF NO, PRINT Z AND LEAVE YEA FALSE.  SPK IS EITHER RSPEK OR MSPEK. 
C 
      IMPLICIT NONE 
C 
      include 'ioccom.fi'
      include 'alphas.fi'
C 
      INTEGER*2 X,Y,Z,REPLY(8),DUMMY(8) 
C 
D     WRITE(CRT,1000) X,Y,Z 
D1000 FORMAT("YESX:",3I8) 
 1010 IF(X.NE.0) CALL SPK(X)  
      CALL GETIN(REPLY,DUMMY,DUMMY) 
      IF(REPLY(1).EQ.CYE .OR. REPLY(1).EQ.CY) THEN
        REPLY(1)=CYE
        REPLY(2)=8275 
      ENDIF 
      IF(REPLY(1).EQ.CN) REPLY(1)=CNO 
      CALL ECHO(REPLY,DUMMY,DUMMY)
      IF(REPLY(1).EQ.CYE) THEN
        YESX=.TRUE. 
        IF(Y.NE.0) CALL SPK(Y)  
      ELSEIF(REPLY(1).EQ.CNO) THEN
        YESX=.FALSE.
        IF(Z.NE.0) CALL SPK(Z)
      ELSE
        CALL MSPEK(30)
        GO TO 1010
      ENDIF
C
      RETURN
      END

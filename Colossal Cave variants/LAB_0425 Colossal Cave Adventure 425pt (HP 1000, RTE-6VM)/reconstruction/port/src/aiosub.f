      DO I=1,LOCSIZ 
        IF(KEY(I).NE.0 .OR. COND(I).NE.0) THEN
          WRITE(OUTLU,1420) I,KEY(I),I,COND(I)
 1420     FORMAT(" KEY array   (",I3,") =",I6,6X, 
     &           " COND array  (",I3,") =",I6)
        ENDIF 
      ENDDO 
      GO TO 20
C 
C  DISPLAY VOCAB INFORMATION
C 
 1500 CALL MSPEK(26)
      READ(KBD,1510,END=9000) ID 
 1510 FORMAT(8A2) 
      CALL CLCUC(ID,8)
      CALL VOCAB(ID,-1,IANS,INDEX)
      IPROP=MOD(IANS,1000)
      WRITE(CRT,1520) IANS,IPROP,ID 
 1520 FORMAT("VOCAB =",I5,",  PROP =",I4,2X,8A2)
      GO TO 20
C 
C  ALTER OUTPUT LU
C 
 1600 WRITE(CRT,1610) OUTLU 
 1610 FORMAT("Current output LU =",I3,", new LU? ",$)
      READ(KBD,*,END=9000) OUTLU 
      GO TO 20
C 
C 
 9000 RETURN
      END 

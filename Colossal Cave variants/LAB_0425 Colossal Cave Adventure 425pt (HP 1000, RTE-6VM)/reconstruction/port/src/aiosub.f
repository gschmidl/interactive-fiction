            BLKLIN=.TRUE. 
          ENDIF 
        ENDIF 
      ENDDO 
      GO TO 20
C 
C  DISPLAY ARYCOM 
C 
 1400 DO I=1,100
        IF(PLAC(I).NE.0 .OR. FIXD(I).NE.0) THEN 
          WRITE(OUTLU,1410) I,PLAC(I),I,FIXD(I) 
 1410     FORMAT(" PLAC array  (",I3,") =",I6,6X, 
     &           " FIXD array  (",I3,") =",I6)
        ENDIF 

      SUBROUTINE SAVE(FILENAME)
C 
C  IF YOU CHANGE THE SIZE OF ANY COMMON, BE SURE TO CHANGE THIS CODE
C  NOTE THAT IOCCOM IS NOT SAVED BUT IS USED FOR COMMUNICATION. 
C 
      IMPLICIT NONE 
C 
      include 'alphas.fi'
      include 'arycom.fi'
      include 'ioccom.fi'
      include 'lincom.fi'
      include 'magcom.fi'
      include 'miscom.fi'
      include 'placom.fi'
      include 'trvcom.fi'
      include 'txtcom.fi'
      include 'voccom.fi'
C 
      LOGICAL*2 YES 
C 
      CHARACTER*(*) FILENAME
      CHARACTER*64 NAME 
C 
      INTEGER*2 I,J,N,ERROR,TRIMLEN,NFIOB 
      LOGICAL*2 NOFILE,HASFILE
      INTEGER*2 ALPDAT(12),ARYDAT(750)
      INTEGER*2 MAGDAT(24),MISDAT(270),PLADAT(551)
      INTEGER*2 TRVDAT(2401),TXTDAT(667),VOCDAT(3061) 
C 
      EQUIVALENCE (BLANK,ALPDAT),(PLAC,ARYDAT)
      EQUIVALENCE (DEMO,MAGDAT),(LINUSE,MISDAT),(ATLOC,PLADAT)
      EQUIVALENCE (TRAVEL,TRVDAT),(ASCVAR,TXTDAT),(KTAB,VOCDAT) 
C 
C  ADD TYPE AND SIZE TO FILE NAME AND THEN OPEN 
C 
      N=TRIMLEN(FILENAME) 
      IF(N.LT.1 .OR. N.GT.55) THEN
        CALL FMPREPORTERROR(-15,FILENAME) 
        RETURN
      ENDIF 
      DO I=1,64 
        IF(I.LE.N) THEN 
          NAME(I:I)=FILENAME(I:I) 
        ELSE
          NAME(I:I)=' ' 
        ENDIF 
      ENDDO 
      DO I=1,N
        IF(NAME(N:N).EQ.':') GO TO 20 
      ENDDO 
C     RTE file type and size suffix; meaningless off the machine.
C     NAME(N+1:N+8)=':::3:300'
C     N=N+8 
C 
   20 CALL CASEFOLD(NAME) 
      OPEN(UNIT=LU,FILE=NAME,STATUS='NEW',ACCESS='SEQUENTIAL',
     &  FORM='UNFORMATTED',IOSTAT=ERROR,ERR=100)
   30 WRITE(CRT,40) NAME(1:N) 
   40 FORMAT(/"Saving data base in file ",A)
C 
C  WRITE REVISION 
C 
      WRITE(LU,IOSTAT=ERROR,ERR=120) REVISION 
C 
C  WRITE ALPHAS 
C 
      WRITE(LU) (ALPDAT(I),I=1,12)
C 
C  WRITE ARYCOM 
C 
      DO I=1,15 
        J=(I-1)*50+1
        WRITE(LU) (ARYDAT(N),N=J,J+49)
      ENDDO 
C 
C  WRITE LINCOM 
C 
      DO I=1,560
        J=(I-1)*50+1
        WRITE(LU) (LINES(N),N=J,J+49) 
      ENDDO 
C 
C  WRITE MAGCOM 
C 
      WRITE(LU) (MAGDAT(I),I=1,24)
C 
C WRITE MISCOM
C 
      DO I=1,5
        J=(I-1)*50+1
        WRITE(LU) (MISDAT(N),N=J,J+49)
      ENDDO 
      WRITE(LU) (MISDAT(I),I=251,270) 
C 
C  WRITE PLACOM 
C 
      DO I=1,11 
        J=(I-1)*50+1
        WRITE(LU) (PLADAT(N),N=J,J+49)
      ENDDO 
      WRITE(LU) HOLDNG
C 
C  WRITE TRVCOM 
C 
      DO I=1,48 
        J=(I-1)*50+1
        WRITE(LU) (TRVDAT(N),N=J,J+49)
      ENDDO 
      WRITE(LU) TRVSIZ
C 
C  WRITE TXTCOM 
C 
      DO I=1,13 
        J=(I-1)*50+1
        WRITE(LU) (TXTDAT(N),N=J,J+49)
      ENDDO 
      WRITE(LU) (TXTDAT(I),I=651,667) 
C 
C  WRITE VOCCOM 
C 
      DO I=1,51 
        J=(I-1)*60+1
        WRITE(LU) (VOCDAT(N),N=J,J+59)
      ENDDO 
      WRITE(LU) TABSIZ
C 
      CLOSE(UNIT=LU)
      RETURN
C 
C  FILE OPEN ERROR
C 
  100 IF(HASFILE(NAME)) THEN 
        WRITE(CRT,110) NAME(1:N)
  110   FORMAT(/"File ",A," already exists.") 
        IF(YES(220,54,54)) THEN 
          OPEN(UNIT=LU,FILE=NAME,STATUS='OLD',ACCESS='SEQUENTIAL',
     &      FORM='UNFORMATTED',IOSTAT=ERROR,ERR=120) 
          GO TO 30
        ENDIF 
        RETURN
      ENDIF 
  120 WRITE(CRT,110) ERROR,NAME(1:N)
  130 FORMAT(/"Error",I5," trying to open file ",A) 
      RETURN
      END 

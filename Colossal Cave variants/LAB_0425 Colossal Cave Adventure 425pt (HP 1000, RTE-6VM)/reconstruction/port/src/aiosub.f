      SUBROUTINE SPEK(WORD)
C 
C  PRINT THE MESSAGE IN WORD N OF LINES ARRAY.
C  PRECEED IT WITH A BLANK LINE UNLESS BLKLIN IS FALSE. 
C 
      IMPLICIT NONE 
C 
      INTEGER*2 WORD,I,N,L,PNT,OLDPNT 
C 
      include 'alphas.fi'
      include 'ioccom.fi'
      include 'lincom.fi'
C 
      N=WORD
D     WRITE(CRT,1000) N 
D1000 FORMAT("Subroutine 'SPEK' entered with N = ",I5)  
      IF(N.EQ.0) RETURN 
      IF(BLKLIN.AND.NOINPT) WRITE(CRT,'(" ")')
      NOINPT=.TRUE. 
      PNT=LINES(N)
      OLDPNT = PNT
 1010 N=N+1 
      L=LINES(N)+N
      IF(LINES(N).LT.1 .OR. LINES(N).GT.44) CALL BUG(28)
      N=N+1 
      IF(LINES(N).NE.EOF) WRITE(CRT,1020) (LINES(I),I=N,L)
      N=L+1 
      PNT=LINES(N)
      IF(PNT .EQ. OLDPNT) GO TO 1010
 1020 FORMAT(44A2)
      RETURN
      END 

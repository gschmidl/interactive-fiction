      SUBROUTINE LOWER(BUFFER)
C 
      IMPLICIT NONE 
C 
      INTEGER*2 I,LEN,TRIMLEN 
      CHARACTER*(*) BUFFER
C 
      LEN=TRIMLEN(BUFFER) 
      IF(LEN.LT.1 .OR. LEN.GT.80) RETURN
      DO I=1,LEN
        IF(BUFFER(I:I).GE.'A' .AND. BUFFER(I:I).LE.'Z') THEN
          BUFFER(I:I)=CHAR(ICHAR(BUFFER(I:I))+32)
        ENDIF 
      ENDDO 
C 
      RETURN
      END 

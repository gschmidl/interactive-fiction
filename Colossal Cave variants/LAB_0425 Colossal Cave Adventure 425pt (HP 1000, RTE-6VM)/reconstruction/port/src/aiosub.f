      SUBROUTINE ECHO(WORD1,WORD2,WORD3)
C 
C  SPELL OUT ABREVEATIONS AND DELETE LITTLE ADVERBS OR ADJATIVES. 
C 
      IMPLICIT NONE 
C 
      include 'ioccom.fi'
      include 'voccom.fi'
C 
      INTEGER*2 WORD1(8),WORD2(8),WORD3(8)
      INTEGER*2 TEMP1(8),TEMP2(8) 
      INTEGER*2 L1,L2,I,J,INDEX 
      INTEGER*2 UPCLR(2),TRIMLEN
      INTEGER*2 MAP(12,14),MAPSIZ 
C 
      CHARACTER*16 MESS1,MESS2
C 
      EQUIVALENCE (TEMP1,MESS1),(TEMP2,MESS2) 
C 
      DATA UPCLR/6977,6989/ 
C 
      DATA MAP/8277,8224,8224,8224,20565,8224,8224,8224,8224,8224,8224,8224, 
     &         8260,8224,8224,8224,20292,20055,8224,8224,8224,8224,8224,8224, 
     &         8270,8224,8224,8224,20302,21586,8264,8224,8224,8224,8224,8224, 
     &         8261,8224,8224,8224,16709,21587,8224,8224,8224,8224,8224,8224, 
     &         8275,8224,8224,8224,20307,21589,8264,8224,8224,8224,8224,8224, 
     &         8279,8224,8224,8224,17751,21587,8224,8224,8224,8224,8224,8224, 
     &         17742,8224,8224,8224,20302,21586,17736,21313,8276,8224,8224,8224, 
     &         22350,8224,8224,8224,20302,21586,22344,21317,8276,8224,8224,8224, 
     &         17747,8224,8224,8224,20307,21589,17736,21313,8276,8224,8224,8224, 
     &         22355,8224,8224,8224,20307,21589,22344,21317,8276,8224,8224,8224, 
     &         8255,8224,8224,8224,17736,20556,8224,8224,8224,8224,8224,8224, 
     &         20565,21587,8274,8224,20565,21587,18753,21330,8224,8224,8224,8224, 
     &         20036,21587,8274,8224,20292,20055,21587,18753,21330,8224,8224,8224, 
     &         12872,8271,8224,8224,16727,17748,8274,8224,8224,8224,8224,8224/ 
      DATA MAPSIZ/14/ 
C 
C  GET RID OF 'A', 'AN', 'AND', 'THE', 'OF', 'TO', 'FROM' FROM SECOND WORD
C  AND REPLACE IT WITH THIRD WORD IF ANY. 
C 
      IF(WORD2(1).NE.0) THEN
        IF(WORD2(1).EQ.8257 .AND. WORD2(2).EQ.8224 .OR. 
     &     WORD2(1).EQ.20033 .AND. WORD2(2).EQ.8224 .OR. 
     &     WORD2(1).EQ.20033 .AND. WORD2(2).EQ.8260 .OR. 
     &     WORD2(1).EQ.18516 .AND. WORD2(2).EQ.8261 .OR. 
     &     WORD2(1).EQ.17999 .AND. WORD2(2).EQ.8224 .OR. 
     &     WORD2(1).EQ.20308 .AND. WORD2(2).EQ.8224 .OR. 
     &     WORD2(1).EQ.21062 .AND. WORD2(2).EQ.19791 ) THEN 
          IF(WORD3(1).NE.0) THEN
            DO I=1,8
              WORD2(I)=WORD3(I) 
              WORD3(I)=0
            ENDDO 
          ENDIF 
        ENDIF 
      ENDIF 
C 
C  COPY WORDS INTO STRING BUFFERS 
C 
      DO I=1,8
        TEMP1(I)=WORD1(I) 
        TEMP2(I)=WORD2(I) 
      ENDDO 
C 
C  MAP ABREVIATIONS TO FULL SPELLING
C 
      DO I=1,MAPSIZ 
        DO J=1,4
          IF(TEMP1(J).NE.MAP(J,I)) GO TO 100
        ENDDO 
        DO J=1,8
          TEMP1(J)=MAP(J+4,I) 
        ENDDO 
  100   DO J=1,4
          IF(TEMP2(J).NE.MAP(J,I)) GO TO 200
        ENDDO 
        DO J=1,8
          TEMP2(J)=MAP(J+4,I) 
        ENDDO 
  200   CONTINUE
      ENDDO 
C 
C  LOOK UP ABREVIATIONS 
C 
      CALL VOCAB(TEMP1,-1,J,INDEX)
      IF(J.GE.0) THEN 
        DO I=1,8
          TEMP1(I)=ATAB(I,INDEX)
        ENDDO 
      ENDIF 
      CALL VOCAB(TEMP2,-1,J,INDEX)
      IF(J.GE.0) THEN 
        DO I=1,8
          TEMP2(I)=ATAB(I,INDEX)
        ENDDO 
      ENDIF 
C 
C  SHIFT TO LOWER CASE AND ECHO BACK TO TERMINAL
C
      L1=TRIMLEN(MESS1)
      IF(L1.LT.1) RETURN
      CALL LOWER(MESS1(2:16))
      L2=TRIMLEN(MESS2)
      IF(L2.LT.1) THEN
        MESS2(1:1)=' '
        L2=1
      ENDIF
      CALL LOWER(MESS2)
!     ESC-A ESC-M ONLY WORKS ON HP TERMS. DISABLED. -DWH
C     WRITE(CRT,300) UPCLR,MESS1(1:L1)//' '//MESS2(1:L2)
  300 FORMAT(2A2,">",A)
C
      RETURN
      END

"""Turn the data files on the NERO0366 disk into C tables for the port.

usage: mkdata.py adventure.dsk out.c

Every HPL data file (types 0x0400 and 0x2400) is written record by record
as the 9825 would read it with rread/sread: numbers and whole strings, split
strings joined into the record where they start (tools/hpldisk.py).  The
game reaches them through asgn "NAME", so they keep their disk names.
ADVSAV is left out: the port keeps the player's save on the host.
"""
import os
import sys
from decimal import Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
import hpldisk  # noqa: E402

SKIP = {'ADVSAV'}


def cstr(s):
    out = []
    for ch in s.encode('latin-1'):
        if ch in (0x22, 0x5c, 0x3f) or ch < 0x20 or ch > 0x7e:
            out.append('\\%03o' % ch)
        else:
            out.append(chr(ch))
    return '"' + ''.join(out) + '"'


def cnum(v):
    if isinstance(v, int):
        return '%d.0' % v
    return repr(float(Decimal(v)))


def main():
    disk = open(sys.argv[1], 'rb').read()
    out = []
    out.append('/* generated by mkdata.py from adventure.dsk - do not edit */')
    out.append('#include "rt.h"')
    files = []
    longest = 0
    for e in hpldisk.directory(disk):
        if e['type'] not in (0x0400, 0x2400) or e['name'] in SKIP:
            continue
        name = e['name']
        recs = hpldisk.records(hpldisk.file_bytes(disk, e))
        rec_names = []
        for rno, items in recs:
            if not items:
                rec_names.append(None)
                continue
            rn = 'd_%s_%d' % (name, rno)
            body = []
            for it in items:
                if isinstance(it, str):
                    if it.startswith('<?'):
                        raise SystemExit('%s record %d: unreadable item %s' % (name, rno, it))
                    longest = max(longest, len(it)) if name.startswith('SEC') else longest
                    body.append('{2,0,%s,%d}' % (cstr(it), len(it.encode('latin-1'))))
                else:
                    body.append('{1,%s,0,0}' % cnum(it))
            out.append('static const HItem %s[] = {%s};' % (rn, ',\n  '.join(body)))
            rec_names.append((rn, len(items)))
        hr = 'r_%s' % name
        out.append('static const HRec %s[] = {' % hr)
        for r in rec_names:
            out.append('  {%d, %s},' % ((r[1], r[0]) if r else (0, '0')))
        out.append('};')
        files.append((name, len(rec_names), hr))
    out.append('const HFile hfiles[] = {')
    for name, n, hr in files:
        out.append('  {"%s", %d, %s},' % (name, n, hr))
    out.append('  {0, 0, 0}')
    out.append('};')
    with open(sys.argv[2], 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('mkdata: %d files, longest SEC string %d' % (len(files), longest))


main()

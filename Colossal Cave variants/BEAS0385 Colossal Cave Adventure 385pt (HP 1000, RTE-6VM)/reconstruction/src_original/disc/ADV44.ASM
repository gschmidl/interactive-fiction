* 
*     SUBROUTINE PUTQ(XQ,I,IASC)
* 
*     PUTS CHARACTER WITH ASCII VALUE IASC INTO THE I-th POSITION OF XQ.
*     DOES NOT CHECK OR MODIFY STRING LENGTH. 
*     I MAY HAVE ANY VALUE POSITIVE OR NEGATIVE.
*     USES ONLY LOWER ORDER EIGHT BIT OF IASC.
*     ARW 6/76
* 

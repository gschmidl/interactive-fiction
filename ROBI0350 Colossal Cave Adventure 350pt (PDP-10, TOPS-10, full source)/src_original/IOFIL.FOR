C	THESE ROUTINES HOPEFULLY DO WHAT THE OLD LIBRARY IFIL
C	AND OFIL ROUTINES DID. WRITTEN AS REPLACEMENTS BY
C	PAUL T. ROBINSON, WESLEYAN UNIV. JUNE 1980
C	DECUS CONVERSION PROGRAMMER
	SUBROUTINE IFILE(IUNIT, NAME, IEXT)
	DOUBLE PRECISION DNAME
	ENCODE(10,10,DNAME) NAME, IEXT
10	FORMAT(2A5)
	OPEN(UNIT=IUNIT,FILE=DNAME,ACCESS='SEQIN')
	RETURN
	END

	SUBROUTINE OFILE(IUNIT,NAME,IEXT)
	DOUBLE PRECISION DNAME
	ENCODE(10,10,DNAME) NAME, IEXT
10	FORMAT(2A5)
	OPEN(UNIT=IUNIT, FILE=DNAME, ACCESS='SEQOUT')
	RETURN
	END

	  ILINKS=((IWORD-1)*5)/4+2
 280	  IF (IOBUF(ILINKS).NE.0) IOBUF(ILINKS)=IOBUF(ILINKS)+IMODFY
 300	 WRITE (1) (IOBUF(I),I=1,500)

	RETURN
	END
	SUBROUTINE SRMBTN(IRMCTR,IRMMAX,INODE1,ILINK1)
	INTEGER*2 IIBUFS(5,250),IOBUF(500)
	LOGICAL*1 LRFLAG
	COMMON /DANDD4/IIBUFS,IR1,IR2
	COMMON /DANDD5/IOBUF,ILEV,LRFLAG
	IMAIN1=INODE1*5-4
	IPT1=IMAIN1+ILINK1
	INODE2=IIBUFS(ILEV,IPT1)-50
	IMAIN2=INODE2*5-4
	IACR1=ILINK1-(-1)**ILINK1
	DO 100 ILINK2=1,4
	 IPT2=IMAIN2+ILINK2
 100	 IF (IIBUFS(ILEV,IPT2).EQ.(INODE1+50)) GOTO 200
	ILINK2=IACR1
	IPT2=IMAIN2+ILINK2
 200	IACR2=ILINK2-(-1)**ILINK2
	ITYPE1=IAND(IIBUFS(ILEV,IMAIN1),3840)/256
	ITYPE2=IAND(IIBUFS(ILEV,IMAIN2),3840)/256
	IF ((ITYPE1.EQ.1).OR.(ITYPE1.GE.5).OR.(ITYPE2.EQ.1).OR.
     X	 (ITYPE2.GE.5)) RETURN
	IIBUFS(ILEV,IPT1)=IRMCTR
	IIBUFS(ILEV,IMAIN1)=IAND(IIBUFS(ILEV,IMAIN1),255)+1280-
     X	 15*2**(ILINK1-1)
	IIBUFS(ILEV,IPT2)=IRMCTR
	IIBUFS(ILEV,IMAIN2)=IAND(IIBUFS(ILEV,IMAIN2),255)
     X	 +1280-15*2**(ILINK2-1)
	IOBUF(IRMCTR*5-4)=1792+(2**IACR1+2**IACR2)/2
	IOBUF(IRMCTR*5-4+IACR2)=INODE2+50
	IOBUF(IRMCTR*5-4+IACR1)=INODE1+50
	IRMCTR=IRMCTR+1
	IF (IRMCTR .GT. IRMMAX) GO TO 800
	CALL SRMTRM(IRMCTR,IRMMAX)
	RETURN
 800	LRFLAG=.TRUE.
	RETURN
	END
	SUBROUTINE SRMTCR(IRMCTR,IRMMAX,INODE,ILINK)
	INTEGER*2 IIBUFS(5,250),IOBUF(500)
	LOGICAL*1 LRFLAG
	COMMON /DANDD4/IIBUFS,IR1,IR2
	COMMON /DANDD5/IOBUF,ILEV,LRFLAG
	IMAIN=INODE*5-4
	IPT=IMAIN+ILINK
	IIBUFS(ILEV,IPT)=IRMCTR
	IIBUFS(ILEV,IMAIN)=IAND(IIBUFS(ILEV,IMAIN),255)+1280+
     X	 2**(ILINK-1)
	IACROS=ILINK-(-1)**ILINK
	IOBUF(IRMCTR*5-4)=1792+2**(IACROS-1)
	IOBUF(IRMCTR*5-4+IACROS)=INODE+50
	IRMCTR=IRMCTR+1
	IF (IRMCTR .GT. IRMMAX) GO TO 800
	CALL SRMTRM(IRMCTR,IRMMAX)
	RETURN
 800	LRFLAG=.TRUE.
	RETURN
	END
	SUBROUTINE SRMTRM(IRMCTR,IRMMAX)
	INTEGER*2 IIBUFS(5,250),IOBUF(500)
	LOGICAL*1 LRFLAG
	COMMON /DANDD4/IIBUFS,IR1,IR2
	COMMON /DANDD5/IOBUF,ILEV,LRFLAG
	NODE=IRMCTR-2
 100	NODE=NODE+1
	MAIN=NODE*5-4
	DO 200 LINK=1,4
	 IPT=MAIN+LINK
	 IF ((IOBUF(IPT).NE.0).OR.(RAN(IR1,IR2).GT..126))GOTO 200
	 IOBUF(IPT)=IRMCTR
	 IACROS=LINK-(-1)**LINK
	 IOBUF(MAIN)=IOBUF(MAIN)+2**(LINK-1)
	 IOBUF(IRMCTR*5-4)=1792+2**(IACROS-1)
	 IOBUF(IRMCTR*5-4+IACROS)=NODE
	 IRMCTR=IRMCTR+1
	 IF (IRMCTR .GT. IRMMAX) GO TO 800
 200	 CONTINUE
	IF (NODE .LT. IRMCTR-1) GO TO 100
	RETURN
 800	LRFLAG=.TRUE.
	RETURN
	END

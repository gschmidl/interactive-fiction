	   IF ((RAN(IR1,IR2).LT..1).AND.(IIBUFS(ILEV,IPT).NE.
     X	    0)) CALL SRMBTN(IRMCTR,50,INODE,ILINK)
	   IF ((RAN(IR1,IR2).LT..28).AND.(IIBUFS(ILEV,IPT).EQ.
     X	    0)) CALL SRMTCR(IRMCTR,50,INODE,ILINK)
 190	   IF (LRFLAG) GO TO 230
 200	  CONTINUE
	 GO TO 150
 230	 DO 250 ICOR=1,250
 250	  IOBUF(ICOR+250)=IIBUFS(ILEV,ICOR)
	 IMODFY=(ILEV-1)*100

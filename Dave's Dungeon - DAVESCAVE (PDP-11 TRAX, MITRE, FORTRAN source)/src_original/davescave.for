	SUBROUTINE SCORRS(NLEVS)
	INTEGER*2 IIBUFS(5,250),IBLOCK(50,50),ITREE(50,7),ISIDE(2)
	COMMON /DANDD4/IIBUFS,I1,I2
	DO 750 ILEV=1,NLEVS
	 DO 10 ISET=1,50
	  DO 5 JSET=1,50
 5	   IBLOCK(ISET,JSET)=0
	  DO 10 JSET=1,7
 10	   ITREE(ISET,JSET)=0
	 ILOC=2
	 IMAX=2
	 ICD=RAN(I1,I2)*50+1
	 JCD=RAN(I1,I2)*50+1
	 IBLOCK(ICD,JCD)=52
	 ITREE(2,6)=ICD
	 ITREE(2,7)=JCD
	 IDIR=RAN(I1,I2)*4+2
	 ITREE(2,1)=5632+2**(IDIR-2)
	 ITREE(2,IDIR)=-1
	 IF (ILEV .NE. 1) GO TO 100
	 IACR=IDIR+(-1)**IDIR
	 ITREE(2,IDIR)=51
	 ITREE(1,1)=2048+2**(IACR-2)
	 ITREE(1,IACR)=52
 100	 DO 500 IDIR=2,5
	  ICD=ITREE(ILOC,6)
	  JCD=ITREE(ILOC,7)
	  IF ((ITREE(ILOC,IDIR).NE.0).OR.(RAN(I1,I2).GE..5)) GOTO 500
	  ICDINC=(IDIR/2-1)*(-1)**IDIR
	  JCDINC=(IDIR/2-2)*(-1)**(IDIR-1)
	  IF (IBLOCK(ICD+ICDINC,JCD+JCDINC).NE.0) GO TO 500
	  IDREM=MOD(IDIR-1,2)*50-ICDINC*ICD-JCDINC*JCD-MOD(IDIR,2)
	  IF (IDREM .LT. 2) GO TO 500
	  IRUN=RAN(I1,I2)*(IDREM-1)+1
	  IF (ITREE(ILOC,1).LT.1280) ITREE(ILOC,1)=ITREE(ILOC,1)+256
	  ITREE(ILOC,1)=ITREE(ILOC,1)+16*2**(IDIR-2)
	  IACR=IDIR+(-1)**IDIR
	  DO 200 IMOVE=1,IRUN
	   ICD=ICD+ICDINC
	   JCD=JCD+JCDINC
	   IF (IBLOCK(ICD,JCD) .NE. 0) GO TO 250
 200	   IBLOCK(ICD,JCD)=-1
	  ICD=ICD+ICDINC
	  JCD=JCD+JCDINC
	  IF (IBLOCK(ICD,JCD) .NE. 0) GO TO 250
	  IMAX=IMAX+1
	  ITREE(ILOC,IDIR)=IMAX+50
	  IBLOCK(ICD,JCD)=IMAX+50
	  ITREE(IMAX,6)=ICD
	  ITREE(IMAX,7)=JCD
	  ITREE(IMAX,1)=256+16*2**(IACR-2)
	  ITREE(IMAX,IACR)=ILOC+50
	  IF (IMAX .EQ. 49) GO TO 600
	  GO TO 500
 250	  IF (IBLOCK(ICD,JCD) .EQ. -1) GO TO 300
	  IBACK=IBLOCK(ICD,JCD)-50
	  ITREE(ILOC,IDIR)=IBACK+50
	  IF (ITREE(IBACK,1).LT.1280) ITREE(IBACK,1)=ITREE(IBACK,1)+256
	  ITREE(IBACK,1)=ITREE(IBACK,1)+16*2**(IACR-2)
	  ITREE(IBACK,IACR)=ILOC+50
	  GO TO 500
 300	  IMAX=IMAX+1
	  ITREE(ILOC,IDIR)=IMAX+50
	  ITREE(IMAX,IACR)=ILOC+50
	  IBLOCK(ICD,JCD)=IMAX+50
	  ITREE(IMAX,6)=ICD
	  ITREE(IMAX,7)=JCD
	  ISIDE(1)=2*(3-IDIR/2)
	  ISIDE(2)=ISIDE(1)+1
	  ITREE(IMAX,1)=768+16*(2**(IACR-2)+2**(ISIDE(1)-2)+2**(ISIDE(2)
     X	   -2))
	  DO 350 ISD=1,2
	   ICDINC=(ISIDE(ISD)/2-1)*(-1)**ISIDE(ISD)
	   JCDINC=(ISIDE(ISD)/2-2)*(-1)**(ISIDE(ISD)-1)
	   ICD2=ICD
	   JCD2=JCD
	   DO 310 IMOVE=1,51
	    ICD2=ICD2+ICDINC
	    JCD2=JCD2+JCDINC
 310	    IF (IBLOCK(ICD2,JCD2).NE.-1) GO TO 320
 320	   IBACK=IBLOCK(ICD2,JCD2)
	   IACR2=ISIDE(3-ISD)
	   ITREE(IMAX,ISIDE(ISD))=IBACK
 350	   ITREE(IBACK-50,IACR2)=IMAX+50
	  IF (IMAX .GE. 49) GO TO 600
 500	  CONTINUE
	 ILOC=ILOC+1
	 IF (ILOC .LE. IMAX) GO TO 100
	 ILOC=RAN(I1,I2)*(ILOC-3)+2
	 GO TO 100
 600	 IF (ILEV .EQ. NLEVS) GO TO 700
	 IDIR=RAN(I1,I2)*4+2
 610	 IDIR=MOD(IDIR-1,4)+2
	 IF (ITREE(49,IDIR) .NE. 0) GO TO 610
	 ITREE(49,1)=1536+IAND(ITREE(49,1),240)+2**(IDIR-2)
	 ITREE(49,IDIR)=152
 700	 DO 740 IMOVE=1,50
	  DO 740 JMOVE=1,5
 740	   IIBUFS(ILEV,(IMOVE-1)*5+JMOVE)=ITREE(IMOVE,JMOVE)
 750	CONTINUE
	RETURN
	END

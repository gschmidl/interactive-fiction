      SUBROUTINE TOOCT(N)
C
C  PORT: PRIMOS'S TOOCT TYPED AN INTEGER*2 AS SIX OCTAL DIGITS WITHOUT A
C  NEWLINE.  PSPEAK PASSES IT AN INTEGER*4 - THE PROGRAM IS COMPILED -INTL -
C  SO ON THE PRIME IT PRINTED THE HIGH-ORDER HALFWORD, WHICH FOR A SMALL
C  NUMBER IS ZERO.  THAT IS WHY THE LEFT-OVER TRACE IN PSPEAK PRINTS
C  "000000 000000" IN FRONT OF EVERY OBJECT ON THE REAL MACHINE, AND WHY IT
C  DOES HERE (SEE ..\README.md).
C
      IMPLICIT INTEGER (A-Z)
C
      H = IAND(ISHFT(N,-16),65535)
      WRITE(6,1)H
1     FORMAT(O6.6,$)
      RETURN
      END
      SUBROUTINE T1OU(N)
C
C  PORT: TYPED ONE CHARACTER FROM AN INTEGER*2.  MEASURED ON THE EMULATOR IT
C  IS THE LOW-ORDER BYTE OF THE HALFWORD - THE SECOND CHARACTER OF A LITERAL
C  - WHICH IS WHY PSPEAK'S T1OU('  ') PRINTS ONE BLANK.
C
      IMPLICIT INTEGER (A-Z)
C
      C = IAND(ISHFT(N,-8),255)
      WRITE(6,1)CHAR(C)
1     FORMAT(A1,$)
      RETURN
      END
      SUBROUTINE TONL
C
C  PORT: TYPED A NEWLINE.
C
      WRITE(6,1)
1     FORMAT(1X)
      RETURN
      END
      SUBROUTINE TODEC(N)
C
C  PORT: TYPED AN INTEGER*2 IN DECIMAL IN SIX COLUMNS, WITHOUT A NEWLINE -
C  AGAIN THE HIGH-ORDER HALFWORD OF WHAT PSPEAK HANDS IT, AND SIGNED.  A
C  NEGATIVE NUMBER PRINTS AS A MINUS SIGN AND THEN THE MAGNITUDE IN FIVE
C  COLUMNS, WHICH IS HOW "-    1" COMES OUT OF THE REAL MACHINE (MEASURED:
C  1, -1, 123, -123, 32767, -32768 GIVE "     1", "-    1", "   123",
C  "-  123", " 32767", "-32768").
C
      IMPLICIT INTEGER (A-Z)
C
      H = IAND(ISHFT(N,-16),65535)
      IF(H.GE.32768)H = H-65536
      IF(H.LT.0)GOTO 10
      WRITE(6,1)H
1     FORMAT(I6,$)
      RETURN
10    WRITE(6,2)-H
2     FORMAT('-',I5,$)
      RETURN
      END

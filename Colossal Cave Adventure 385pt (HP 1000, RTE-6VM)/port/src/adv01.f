      INTEGER*2 FUNCTION RNDM(RANGE)
C
C A VARIANT USING THE RANDOM NUMBER GENERATOR IN FORLIB.
C
      IMPLICIT INTEGER*2 (A-Z)
      REAL RANDM,SEED
      DIMENSION IPAR(5)
      EQUIVALENCE (I,SEED),(I,IPAR(1)),(J,IPAR(2)),(K,IPAR(3))
      DATA R/0/
C
      IF(R.NE.0) GO TO 1
      R=1
      CALL EXEC(11,IPAR)
      I=IOR(I,K)
      J=IOR(J,K)
1     RNDM= RANDM(SEED) *REAL(RANGE)
C
      RETURN
      END

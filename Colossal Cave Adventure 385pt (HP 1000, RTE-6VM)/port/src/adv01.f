C     26    LOCATION HAS NO TRAVEL ENTRIES
C     27    HINT NUMBER EXCEEDS GOTO LIST
C     28    INVALID MONTH RETURNED BY DATE FUNCTION
C
      WRITE(LU,1) NUM
1     FORMAT (" FATAL ERROR ",I3,", CONSULT YOUR LOCAL WIZARD."/)
      STOP
      END
